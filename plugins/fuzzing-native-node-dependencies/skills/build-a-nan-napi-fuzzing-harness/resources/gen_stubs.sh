#!/bin/bash
# Generate trapping stubs for the binding-runtime symbols that the addon objects you
# link reference but do not define.  Never hand-write this list.
#
#   gen_stubs.sh <objects...> > stubs.cc
#   afl-clang-fast++ -c -o stubs.o stubs.cc
#
# Covers both Node binding ABIs and the raw runtime underneath them:
#   N-API            napi_* / node_api_*     plain C names, no asm label needed
#   node-addon-api   Napi::*                 mangled C++  -> bound via asm label
#   NAN / raw V8     v8::* / node::*          mangled C++  -> bound via asm label
#   plus the PACKAGE's own helpers that take binding types anywhere in their
#   signature (pkg::toJsError(Napi::Env, ...)), which is what you get once a
#   hand-written binding is split across translation units.
#
# Matching is done on the DEMANGLED name, as a namespace token: `Napi::`, `v8::` or
# `node::` not preceded by another `::`.  An earlier version grepped the mangled text
# for `4node`, which also matched any library symbol containing a four-letter
# identifier `node` (lib::node::foo, std::vector<foo::node>) and stubbed it.
#
# Symbols DEFINED by any object in the set are excluded: a helper defined in one addon
# object and referenced from another is not a runtime symbol, and stubbing it would
# give a duplicate definition at link time.
#
# Three rules, each learned the hard way:
#  1. Stubs must DIE, never return.  A stub that returns 0 turns "my harness
#     wandered into binding code" into silent wrong behaviour.
#  2. They must die IDENTIFIABLY.  A bare __builtin_trap() is ambiguous: SIGTRAP is
#     also how ASAN aborts on aarch64, so rc=133 alone cannot distinguish "entered
#     the binding" from "sanitizer reported a stack overflow".
#  3. Self-test one at build time (stubtest.cc), or "no stub was hit during the
#     gate" is unfalsifiable.
#
# extern "C" void f(void) is fine regardless of the real signature: C linkage
# carries no type information and you intend never to call it.
#
#   NAMESPACES   override the C++ namespace list (default "Napi v8 node").  Add the
#                PACKAGE's own namespace ("Napi v8 node <pkg>") when a linked addon object
#                references package methods you do not link -- an inline AsyncWorker or
#                helper in a shared header pulls `<pkg>::Stream::method()` into every TU,
#                and its signature carries no binding type, so the default rule skips it
#                and the link fails with `undefined reference to <pkg>::...`.  The stub is
#                right when the harness never reaches it; gate check 5 then proves that.
#   C_SYMBOLS    override the C-linkage regex (default: napi_*, node_api_*, uv_*,
#                node_module_register -- the last is what every NAN addon's
#                registration block references)
set -euo pipefail
[ $# -ge 1 ] || { echo "usage: $0 <object files...>" >&2; exit 2; }
NS=${NAMESPACES:-Napi v8 node}
NS_RE=$(printf '%s|' $NS); NS_RE=${NS_RE%|}
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT

for o in "$@"; do nm -u "$o"; done | awk '{print $NF}' | sort -u > "$T/undef"
for o in "$@"; do nm --defined-only "$o" 2>/dev/null; done | awk 'NF{print $NF}' | sort -u > "$T/def"
comm -23 "$T/undef" "$T/def" > "$T/need"

{
  cat <<'HDR'
// generated by gen_stubs.sh -- do not edit
#include <unistd.h>
#include <string.h>
static void afl_stub_hit(const char* name) {
  (void)!write(2, "AFL-HARNESS-STUB: entered binding runtime: ", 43);
  (void)!write(2, name, strlen(name));
  (void)!write(2, "\n", 1);
  __builtin_trap();
}
extern "C" {
HDR
  # N-API: plain C entry points
  grep -E "${C_SYMBOLS:-^(napi|node_api|uv)_[A-Za-z0-9_]+\$|^node_module_register\$}" "$T/need" \
    | awk '{ printf "void %s(void){ afl_stub_hit(\"%s\"); }\n", $1, $1 }' || true
  # Mangled C++: demangle, keep names mentioning a binding namespace as a token
  grep -E '^_Z' "$T/need" > "$T/mangled" || true
  if [ -s "$T/mangled" ]; then
    c++filt < "$T/mangled" > "$T/demangled"
    paste "$T/mangled" "$T/demangled" \
      | grep -E "(^|[^A-Za-z0-9_:])(${NS_RE})::" \
      | awk -F'\t' '{ printf "void afl_cxx_stub_%d(void) __asm__(\"%s\");  // %s\n", NR, $1, $2;
                      printf "void afl_cxx_stub_%d(void){ afl_stub_hit(\"%s\"); }\n", NR, $1 }' || true
  fi
  echo '}'
}
