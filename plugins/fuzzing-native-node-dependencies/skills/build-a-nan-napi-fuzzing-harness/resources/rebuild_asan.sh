#!/bin/bash
# The REBUILD step for detect_selftest.sh on a node-gyp package: rebuild the asan
# variant of the addon (which recompiles the patched library source) and relink the
# asan harness.  Pass the SAME KEY=VALUE arguments you gave build_addon.sh and
# link_harness.sh; both ignore the ones they do not use.
#
#   REBUILD="resources/rebuild_asan.sh PKGDIR=/path/to/pkg OUT=/abs/fuzz/out \
#            MK=/abs/fuzz/out/asan/<target>.target.mk SRCDIR=/path/to/pkg \
#            HARNESS=/abs/fuzz/harness.cc LIB='...' [ADDON_OBJS='...'] [EXTRA_LIBS='...'] \
#            [TARGET=<gyp target>] [EXTRA_LDFLAGS=-Wl,-Bsymbolic] [EXTRA_CFLAGS='...']"
#
# EXTRA_CFLAGS / EXTRA_LDFLAGS: when NOT given, the values the last asan build_addon.sh run
# used are reused from OUT/asan/extra_flags.env, so an addon built -Bsymbolic (because
# check_symbols.sh reported INTERPOSED) stays -Bsymbolic after the self-test's rebuilds.
# Give EXTRA_LDFLAGS= (empty) to drop it.
#
# Route 3b (a static archive from build_lib.sh): when OUT/asan/lib-build/build_lib.args
# exists, build_lib.sh VARIANT=asan is replayed with those recorded arguments first (an
# incremental build of the library tree, so the fault patched into its SRC is compiled in),
# then the addon (only when PKGDIR is given; the addon does not hold the library) and the
# harness link.  OUT must be the same absolute OUT the build used:
#   REBUILD="$R/rebuild_asan.sh OUT=$W/out MK=$W/out/asan/<target>.target.mk SRCDIR=<pkg> \
#            HARNESS=$W/harness.cc LIB=$W/out/asan/lib/lib<x>.a [ADDON_OBJS='...'] [EXTRA_LIBS='...']"
#
# NOT usable when the library is extracted or regenerated by a gyp ACTION during
# configure (a tarball-vendored compression binding untars its library; anything that runs its own configure): the rebuild
# then overwrites the file you patched.  For those, configure the library once
# out-of-tree with CC=afl-clang-fast AFL_USE_ASAN=1, and make REBUILD a `make` in that
# tree plus a relink of the harness -- see detect_selftest.sh's header.
set -uo pipefail
for kv in "$@"; do case $kv in *=*) export "$kv";; esac; done
# PKGDIR, not PKG: fuzz.env exports PKG as the ORACLE path, and a rebuild.sh that forgot the
# argument would otherwise cd into the oracle and rebuild there.  PKG= is still accepted as
# the package dir only when it holds a binding.gyp AND its path has no /oracle/ or
# /node_modules/: an oracle built from source on install holds a binding.gyp too.
PKGDIR=${PKGDIR:-}
HERE=$(cd "$(dirname "$0")" && pwd)
# a library built by build_lib.sh: replay its recorded arguments (one KEY=VALUE per line)
LIBARGS=""
findlib() { local o; for o in "${OUT:-out}" "${PKGDIR:+$PKGDIR/${OUT:-out}}"; do
  [ -n "$o" ] && [ -f "$o/asan/lib-build/build_lib.args" ] && { LIBARGS=$o/asan/lib-build/build_lib.args; LIBOUT=$(cd "$o" && pwd); return; }
done; }
findlib
# with a build_lib.sh library and no PKGDIR the addon is not rebuilt, so PKG is not consulted
if [ -z "$PKGDIR" ] && [ -z "$LIBARGS" ] && [ -n "${PKG:-}" ]; then
  case /${PKG#/}/ in
    */oracle/*|*/node_modules/*)
      echo "FAIL: PKG=$PKG looks like the oracle install (/oracle/ or /node_modules/ in the path): rebuilding" >&2
      echo "      there would patch the oracle, not the build tree.  Pass PKGDIR=<package source dir>." >&2
      exit 2;;
  esac
  [ -f "$PKG/binding.gyp" ] && PKGDIR=$PKG
fi
[ -z "$LIBARGS" ] && [ -n "$PKGDIR" ] && findlib
[ -n "$PKGDIR$LIBARGS" ] || { echo "FAIL: set PKGDIR=<package dir, where binding.gyp is> (PKG=${PKG:-unset} is fuzz.env's oracle path, not the source)" >&2; exit 2; }
export AFL_USE_ASAN=1
if [ -n "$LIBARGS" ]; then
  mapfile -t la < "$LIBARGS"
  echo "rebuild_asan.sh: library: build_lib.sh VARIANT=asan OUT=$LIBOUT ${la[*]} (recorded in $LIBARGS)"
  ( unset SRC BUILD CMAKE_ARGS MESON_ARGS CONFIGURE_ARGS MAKE_ARGS TARGET ARCHIVES INC EXTRA_CFLAGS
    "$HERE/build_lib.sh" VARIANT=asan OUT="$LIBOUT" "${la[@]}" ) || exit 1
fi
xf=${OUT:-out}/asan/extra_flags.env; case $xf in /*) ;; *) xf=${PKGDIR:-.}/$xf;; esac   # build_addon.sh runs in PKGDIR
if [ -f "$xf" ]; then
  for k in EXTRA_CFLAGS EXTRA_LDFLAGS; do
    [ -n "${!k+x}" ] && continue
    v=$(. "$xf" && printf '%s' "${!k}")
    [ -n "$v" ] && { export "$k=$v"; set -- "$@" "$k=$v"; echo "rebuild_asan.sh: $k=$v (from $xf, the last asan build)"; }
  done
fi
# output is NOT discarded: detect_selftest.sh captures it as the build log it shows you
# when the faulted rebuild fails
if [ -n "$PKGDIR" ]; then ( cd "$PKGDIR" && "$HERE/build_addon.sh" VARIANT=asan "$@" ) || exit 1
else echo "rebuild_asan.sh: no PKGDIR: the addon is not rebuilt (the library is the archive above)"; fi
"$HERE/link_harness.sh" VARIANT=asan "$@"
