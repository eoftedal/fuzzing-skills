#!/bin/bash
# Generate trapping stubs for the Ruby-runtime symbols that the extension objects you
# link reference but do not define.  Never hand-write this list.
#
#   gen_stubs.sh <objects...> > stubs.cc
#   afl-clang-fast++ -c -o stubs.o stubs.cc
#
# The set is EXACT, not a name pattern: every undefined symbol of the objects that the
# Ruby runtime itself exports (`nm -D --defined-only` of libruby.so, or of the ruby
# executable when Ruby was built without --enable-shared).  That catches rb_*, ruby_*,
# st_*, onig*, Onig*, dln_*, setproctitle ... and nothing from libc or the library.
# Ruby's C API is all C linkage, so there is no demangling and no asm label.
#
# Ruby exports DATA as well as functions: rb_cObject, rb_eArgError, rb_mKernel ... are
# global VALUEs that the glue reads (and that inline header helpers such as rb_class_of
# read).  A function stub cannot trap a read, so libruby's own symbol type decides:
#   T             -> a function that prints the marker and traps when called
#   B / D / R / V -> a read-only page of its own (64 KiB-aligned), made PROT_NONE by a
#                    constructor; a read or
#                    write faults, and a SIGSEGV/SIGBUS handler that recognises the page
#                    prints the marker naming the symbol, then traps.  Faults elsewhere
#                    go to the previous handler (ASAN's, when there is one).
#
# Symbols DEFINED by any object in the set, or by DEFINED_ELSEWHERE, are excluded: a
# helper defined in one extension object and referenced from another is not a runtime
# symbol, and stubbing it would give a duplicate definition at link time.
#
# Three rules, each learned the hard way (on the Node sibling of this skill):
#  1. Stubs must DIE, never return.  A stub that returns 0 turns "my harness wandered
#     into binding code" into silent wrong behaviour.  For data, that means a value
#     the harness can read without faulting is not a stub.
#  2. They must die IDENTIFIABLY.  A bare __builtin_trap() is ambiguous: SIGTRAP is
#     also how ASAN aborts on aarch64, so rc=133 alone cannot distinguish "entered
#     the runtime" from "sanitizer reported a stack overflow".
#  3. Self-test one of each kind at build time (stubtest.cc), or "no stub was hit
#     during the gate" is unfalsifiable.
#
#   RUBY_RUNTIME       the file whose exports are "the runtime" (default: libruby.so of
#                      `ruby` on PATH, else the ruby executable itself)
#   DEFINED_ELSEWHERE  objects/archives also linked (the library: LIB=); their
#                      definitions are excluded
#   C_SYMBOLS          fallback regex, used only when no runtime file can be read
#                      (default ^(rb|ruby|st|onig|onigenc)_ ; every match becomes a
#                      FUNCTION stub, so data reads go untrapped -- say so)
set -euo pipefail
[ $# -ge 1 ] || { echo "usage: $0 <object files...>" >&2; exit 2; }
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT

if [ -z "${RUBY_RUNTIME:-}" ] && command -v ruby >/dev/null 2>&1; then
  RUBY_RUNTIME=$(ruby -e 'c = RbConfig::CONFIG
    if c["ENABLE_SHARED"] == "yes"
      d = [c["libdir"], c["archlibdir"]].compact.find { |x| File.exist?(File.join(x, c["LIBRUBY_SO"])) }
      print File.join(d, c["LIBRUBY_SO"]) if d
    end' 2>/dev/null || true)
  if [ -z "$RUBY_RUNTIME" ]; then     # static libruby, or a distro that renamed the .so
    RUBY_RUNTIME=$(ldd "$(command -v ruby)" 2>/dev/null | awk '/libruby/{print $3; exit}')
    [ -n "$RUBY_RUNTIME" ] || RUBY_RUNTIME=$(command -v ruby)
  fi
fi

for o in "$@"; do nm -u "$o"; done | awk '{print $NF}' | sort -u > "$T/undef"
for o in "$@" ${DEFINED_ELSEWHERE:-}; do nm --defined-only "$o" 2>/dev/null; done | awk 'NF{print $NF}' | sort -u > "$T/def"
comm -23 "$T/undef" "$T/def" > "$T/need"

if [ -n "${RUBY_RUNTIME:-}" ] && nm -D --defined-only "$RUBY_RUNTIME" > "$T/rt.raw" 2>/dev/null && [ -s "$T/rt.raw" ]; then
  echo "gen_stubs: runtime = $RUBY_RUNTIME" >&2
  awk 'NF>=3{print $3, $2}' "$T/rt.raw" | sed 's/@.*\( [A-Za-z]\)$/\1/' | sort -u -k1,1 > "$T/rt"
  join "$T/rt" "$T/need" > "$T/hit"                     # "<sym> <type>"
  awk '$2 ~ /^[TtWwi]$/ {print $1}' "$T/hit" > "$T/fn"
  awk '$2 !~ /^[TtWwi]$/ {print $1}' "$T/hit" > "$T/data"
else
  echo "gen_stubs: WARN no Ruby runtime to read (RUBY_RUNTIME=${RUBY_RUNTIME:-unset}); falling back to C_SYMBOLS, data reads are NOT trapped" >&2
  grep -E "${C_SYMBOLS:-^(rb|ruby|st|onig|onigenc)_}" "$T/need" > "$T/fn" || true
  : > "$T/data"
fi
echo "gen_stubs: $(wc -l < "$T/fn") function + $(wc -l < "$T/data") data stubs" >&2

{
  cat <<'HDR'
// generated by gen_stubs.sh -- do not edit
#include <signal.h>
#include <stdint.h>
#include <string.h>
#include <sys/mman.h>
#include <unistd.h>
static void afl_stub_hit(const char* name) {
  (void)!write(2, "AFL-HARNESS-STUB: entered Ruby runtime: ", 40);
  (void)!write(2, name, strlen(name));
  (void)!write(2, "\n", 1);
  __builtin_trap();
}
extern "C" {
HDR
  awk '{ printf "void %s(void){ afl_stub_hit(\"%s\"); }\n", $1, $1 }' "$T/fn"
  echo '}'
  if [ -s "$T/data" ]; then
    # 64 KiB: the largest page size Linux uses on aarch64, so one symbol never shares a
    # page with anything else whatever the kernel's page size is.  Inside an
    # extern "C" { } block: the one-line `extern "C" T x[N];` form is only a
    # declaration in C++, and the symbols would stay undefined.
    # const + initialised, so they land in a READ-ONLY segment: LeakSanitizer scans
    # every writable segment at exit, and on a PROT_NONE page in .bss it dies with
    # SIGSEGV ("LeakSanitizer has encountered a fatal error") on every clean run.
    cat <<'HDR'
#define AFL_STUB_PAGE 65536
#define AFL_DATA_STUB(sym) \
  __attribute__((aligned(AFL_STUB_PAGE), no_sanitize("address"), used)) \
  extern const unsigned char sym[AFL_STUB_PAGE] = {1};
extern "C" {
HDR
    awk '{ printf "AFL_DATA_STUB(%s)\n", $1 }' "$T/data"
    echo '}'
    echo 'static const unsigned char* const afl_data_stub_addr[] = {'
    awk '{ printf "  %s,\n", $1 }' "$T/data"
    echo '};'
    echo 'static const char* const afl_data_stub_name[] = {'
    awk '{ printf "  \"%s\",\n", $1 }' "$T/data"
    echo '};'
    cat <<'TAIL'
static const int afl_data_stub_n = sizeof(afl_data_stub_addr) / sizeof(*afl_data_stub_addr);
static struct sigaction afl_prev_segv, afl_prev_bus;
static void afl_data_fault(int sig, siginfo_t* si, void* uc) {
  uintptr_t a = (uintptr_t)si->si_addr;
  for (int i = 0; i < afl_data_stub_n; i++) {
    uintptr_t b = (uintptr_t)afl_data_stub_addr[i];
    if (a >= b && a < b + AFL_STUB_PAGE) afl_stub_hit(afl_data_stub_name[i]);
  }
  struct sigaction* p = sig == SIGBUS ? &afl_prev_bus : &afl_prev_segv;
  if (p->sa_flags & SA_SIGINFO) { p->sa_sigaction(sig, si, uc); return; }
  if (p->sa_handler != SIG_DFL && p->sa_handler != SIG_IGN) { p->sa_handler(sig); return; }
  signal(sig, SIG_DFL);                 // no previous handler: re-fault into the default
}
// Runs after ASAN's own init (preinit), so ASAN's SEGV handler is the one chained to.
__attribute__((constructor)) static void afl_data_stubs_arm(void) {
  struct sigaction sa; memset(&sa, 0, sizeof sa);
  sa.sa_sigaction = afl_data_fault; sa.sa_flags = SA_SIGINFO | SA_ONSTACK | SA_NODEFER;
  sigemptyset(&sa.sa_mask);
  sigaction(SIGSEGV, &sa, &afl_prev_segv);
  sigaction(SIGBUS, &sa, &afl_prev_bus);
  for (int i = 0; i < afl_data_stub_n; i++)
    if (mprotect((void*)afl_data_stub_addr[i], AFL_STUB_PAGE, PROT_NONE) != 0) {
      (void)!write(2, "AFL-HARNESS-STUB: mprotect failed; data stubs are unarmed\n", 58);
      __builtin_trap();
    }
}
TAIL
  fi
}
