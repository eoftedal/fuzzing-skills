#!/usr/bin/env ruby
# Generate enc_table.h: every name Ruby's encoding lookup accepts (Encoding.name_list,
# all aliases, case-insensitive) mapped to an index into ONE table of distinct
# encodings -- from the RUNTIME that runs the gem, never typed in.
#
#   ruby resources/gen_enc_table.rb > enc_table.h
#
# enc_names[] ends with a {0, -1} sentinel: iterate `for (i = 0; enc_names[i].name; i++)`,
# not over sizeof -- a sizeof loop passed the sentinel's NULL to strcasecmp and crashed
# (rc=139, measured).  Lookup, case-insensitive like Ruby:
#   int enc_index(const char *n) {
#     for (int i = 0; enc_names[i].name; i++) if (!strcasecmp(enc_names[i].name, n)) return enc_names[i].idx;
#     return -1;   /* Encoding.find raises ArgumentError; rb_enc_find returns ASCII-8BIT */
#   }
#
# For a shim of rb_enc_find / rb_enc_find_index / rb_to_encoding (ruby_shim_template.c),
# and for harnesses that must mirror a Ruby-side Encoding.find (it raises ArgumentError
# for names a C library may accept, e.g. UCS-4 and ebcdic-us).  Two runtime
# behaviours the table encodes, both measured on Ruby 3.3:
#   * rb_enc_find of an UNKNOWN name returns ASCII-8BIT (index 0), not NULL
#     (rb_enc_from_index(idx < 0 ? 0 : idx)); Encoding.find raises ArgumentError instead.
#   * Encoding.find also accepts the special names internal/external/locale/filesystem,
#     whose target depends on the process (they are listed with the index this
#     generating process resolved them to -- regenerate in the environment you gate in).
names = {}
Encoding.list.each_with_index { |e, i| e.names.each { |n| names[n.downcase] = i } }
Encoding.name_list.each do |n|
  e = (Encoding.find(n) rescue nil)
  next unless e
  names[n.downcase] ||= Encoding.list.index(e)
end
idx = ->(e) { Encoding.list.index(e) }
puts "/* generated by gen_enc_table.rb on ruby #{RUBY_VERSION} (#{RUBY_PLATFORM}); do not edit */"
puts "#define ENC_COUNT #{Encoding.list.size}"
puts "#define ENC_ASCII_8BIT_INDEX #{idx.(Encoding::ASCII_8BIT)}"
puts "#define ENC_UTF8_INDEX #{idx.(Encoding::UTF_8)}"
puts "#define ENC_US_ASCII_INDEX #{idx.(Encoding::US_ASCII)}"
puts "static const struct { const char *name; int idx; } enc_names[] = {"
names.sort.each { |n, i| puts "  {#{n.inspect}, #{i}},  /* #{Encoding.list[i].name} */" }
puts "  {0, -1}"
puts "};"
puts "static const char *const enc_canonical[ENC_COUNT] = {"
Encoding.list.each { |e| puts "  #{e.name.inspect}," }
puts "};"
